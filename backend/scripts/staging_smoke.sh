#!/usr/bin/env sh
# Smoke test of the local staging stack, over HTTPS through Caddy (C4.0).
# Run via `make staging/smoke` after `make staging/up` and `make staging/seed`.
#
# It checks that the running stack accepts exactly what deploy/local/.env says:
#   1. the Super Admin (ADMIN_EMAIL / ADMIN_PASSWORD) can log in
#   2. a firm owner (the seeded demo firm) can log in
#   3. a webhook signed with PAYHERO_WEBHOOK_SECRET is accepted, a badly
#      signed one is refused, and the signed one leaves nothing behind
#   4. every health endpoint is green, on both APIs and both web apps
#
# deploy/local/.env is read as data, never sourced (values contain spaces), and
# backend/.env is never read. curl -k because Caddy's local CA is regenerated by
# every `staging/reset`; this only ever talks to *.willcoll.localhost.
set -u

cd "$(dirname "$0")/.."
ENV_FILE="${STAGING_ENV:-../deploy/local/.env}"
[ -f "$ENV_FILE" ] || { echo "no $ENV_FILE: run make staging/up first"; exit 1; }

val() { grep -m1 "^$1=" "$ENV_FILE" | cut -d= -f2-; }

PLATFORM_ORIGIN="$(val PLATFORM_ORIGIN)"
RENTALS_ORIGIN="$(val RENTALS_ORIGIN)"
ADMIN_EMAIL="$(val ADMIN_EMAIL)"
ADMIN_PASSWORD="$(val ADMIN_PASSWORD)"
WEBHOOK_SECRET="$(val PAYHERO_WEBHOOK_SECRET)"
OWNER_EMAIL="${SMOKE_OWNER_EMAIL:-demo@willcoll.test}"
OWNER_PASSWORD="${SMOKE_OWNER_PASSWORD:-Demo-Password-1}"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
fails=0

ok()   { echo "  ok    $1"; }
fail() { echo "  FAIL  $1"; fails=$((fails + 1)); }

# status METHOD URL [curl args...] prints the HTTP status; the body goes to $TMP/body.
status() {
	method="$1"; url="$2"; shift 2
	curl -sk -o "$TMP/body" -w '%{http_code}' -X "$method" "$url" "$@" 2>/dev/null || echo 000
}

expect() { # expect WANT GOT LABEL
	if [ "$2" = "$1" ]; then ok "$3 ($2)"; else fail "$3: want $1, got $2"; fi
}

echo "== sign-in"
code=$(status POST "$PLATFORM_ORIGIN/_platform/v1/admin/sessions" -c "$TMP/admin.jar" \
	-H 'Content-Type: application/json' -d "{\"email\":\"$ADMIN_EMAIL\",\"password\":\"$ADMIN_PASSWORD\"}")
expect 200 "$code" "Super Admin logs in with ADMIN_EMAIL/ADMIN_PASSWORD from $ENV_FILE"

code=$(status POST "$PLATFORM_ORIGIN/_platform/v1/sessions" -c "$TMP/owner.jar" \
	-H 'Content-Type: application/json' -d "{\"email\":\"$OWNER_EMAIL\",\"password\":\"$OWNER_PASSWORD\"}")
expect 200 "$code" "firm owner $OWNER_EMAIL logs in"

echo "== webhook"
# A failed push with a reference nothing knows: it is verified and acknowledged,
# and has no effect (no payment, no unclaimed receipt), so the smoke test can be
# run any number of times.
hook="$RENTALS_ORIGIN/v1/webhooks/payhero/collections"
body='{"response":{"Status":"Failed","ResultCode":1,"ExternalReference":"smoke-test-no-such-intent","CheckoutRequestID":"smoke","ResultDesc":"smoke test"}}'
sig=$(printf '%s' "$body" | openssl dgst -sha256 -hmac "$WEBHOOK_SECRET" -hex | sed 's/.* //')
code=$(status POST "$hook" -H "X-Payhero-Signature: $sig" -d "$body")
expect 200 "$code" "webhook signed with PAYHERO_WEBHOOK_SECRET is accepted"
code=$(status POST "$hook" -H "X-Payhero-Signature: 0000" -d "$body")
expect 401 "$code" "webhook with a bad signature is refused"
code=$(status POST "$hook" -d "$body")
expect 401 "$code" "unsigned webhook is refused"

echo "== health"
code=$(status GET "$PLATFORM_ORIGIN/_platform/v1/healthcheck")
expect 200 "$code" "platform-api /v1/healthcheck"
code=$(status GET "$RENTALS_ORIGIN/v1/healthcheck")
expect 200 "$code" "rentals-api /v1/healthcheck"
code=$(status GET "$PLATFORM_ORIGIN/auth/login")
expect 200 "$code" "platform web app"
code=$(status GET "$RENTALS_ORIGIN/auth/login")
expect 200 "$code" "rentals web app"

# The Super Admin health pages report "available" when every service is ok and
# "degraded" otherwise (system_health.go); list what is wrong if it is not.
for page in "platform-api|$PLATFORM_ORIGIN/_platform/v1/admin/system/health" "rentals-api|$RENTALS_ORIGIN/v1/admin/system/health"; do
	name="${page%%|*}"; url="${page#*|}"
	code=$(status GET "$url" -b "$TMP/admin.jar")
	if [ "$code" != 200 ]; then
		fail "$name Super Admin health page: HTTP $code"
	elif grep -q '"status": "degraded"' "$TMP/body"; then
		fail "$name health is degraded"
		grep -B3 '"status": "\(degraded\|error\|down\|failed\)"' "$TMP/body" | head -20
	elif grep -q '"status": "available"' "$TMP/body"; then
		ok "$name Super Admin health page is available (no degraded service)"
	else
		fail "$name health page has no top-level status"
	fi
done

echo
if [ "$fails" -eq 0 ]; then echo "staging smoke: all checks passed"; else echo "staging smoke: $fails check(s) FAILED"; exit 1; fi
