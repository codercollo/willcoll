func isWriteMethod(m string) bool {
	switch m {
	case "POST", "PUT", "PATCH", "DELETE":
		return true
	}
	return false
}

// handlerCallsAudit reports whether handler's source calls app.audit( or
// app.auditAdmin( anywhere in its body.
//
// handler is a bound method value (app.fooHandler); its PC resolves to a
// compiler-generated "-fm" wrapper with no real source location
// ("<autogenerated>"), and reflect can't look up an unexported method by
// name (Go's reflect only lists exported methods, regardless of caller
// package) — so instead of runtime/reflect, this greps every source file
// in the package for the method's own "func (app *application) name("
// declaration and scans from there to the next top-level "func".
func handlerCallsAudit(t *testing.T, handler gin.HandlerFunc) bool {
	t.Helper()
	wrapperName := runtime.FuncForPC(reflect.ValueOf(handler).Pointer()).Name()
	methodName := strings.TrimSuffix(wrapperName[strings.LastIndex(wrapperName, ".")+1:], "-fm")

	files, err := filepath.Glob("*.go")
	if err != nil {
		t.Fatalf("listing source files: %v", err)
	}
	decl := "func (app *application) " + methodName + "("
	for _, file := range files {
		if strings.HasSuffix(file, "_test.go") {
			continue
		}
		b, err := os.ReadFile(file)
		if err != nil {
			t.Fatalf("reading %s: %v", file, err)
		}
		idx := strings.Index(string(b), decl)
		if idx < 0 {
			continue
		}
		lines := strings.Split(string(b[idx:]), "\n")
		for i, line := range lines {
			if i > 0 && strings.HasPrefix(line, "func ") {
				break // reached the next top-level function
			}
			trimmed := strings.TrimSpace(line)
			if strings.HasPrefix(trimmed, "//") {
				continue // a commented-out call doesn't count
			}
			if strings.Contains(line, "app.audit(") || strings.Contains(line, "app.auditAdmin(") {
				return true
			}
		}
		return false
	}
	t.Fatalf("could not find declaration %q in any source file", decl)
	return false
}

// TestAuditCoverage walks every registered route (build-phases.txt 3f-4):
// every write route must be classified in auditCoverage as "audited" (and
// its handler source must actually call app.audit/app.auditAdmin) or
// "exempt: <reason>". A route missing from the map fails the test, forcing
// a deliberate classification for anything new.
func TestAuditCoverage(t *testing.T) {
	app := &application{}
	app.config.cors.trustedOrigins = []string{"http://localhost:3000"}
	router, err := app.routes()
	if err != nil {
		t.Fatal(err)
	}

	registered := map[string]bool{}
	for _, r := range router.Routes() {
		if !isWriteMethod(r.Method) {
			continue
		}
		key := r.Method + " " + r.Path
		registered[key] = true
		classification, ok := auditCoverage[key]
		if !ok {
			t.Errorf("%s is not classified in auditCoverage: add it as audited (and call app.audit/app.auditAdmin in the handler) or exempt with a reason", key)
			continue
		}
		if classification == "audited" {
			if !handlerCallsAudit(t, r.HandlerFunc) {
				t.Errorf("%s is classified audited but its handler never calls app.audit/app.auditAdmin", key)
			}
		} else if !strings.HasPrefix(classification, "exempt:") {
			t.Errorf("%s has an unrecognized classification %q (want \"audited\" or \"exempt: <reason>\")", key, classification)
		}
	}

	// A classification for a route that no longer exists is a stale claim
	// (e.g. a retired route's "audited" left behind): drop it.
	for key := range auditCoverage {
		if !registered[key] {
			t.Errorf("auditCoverage lists %s, but no such write route is registered: remove it", key)
		}
	}
}
